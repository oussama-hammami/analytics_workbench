def _page_chrome() -> None:
    st.markdown(_CSS, unsafe_allow_html=True)
    st.markdown(
        "<div class='wiz-hero'>"
        "<h1>⚙️ Analytics Workbench</h1>"
        "<p>Installation Wizard — configure your instance in a few steps.</p>"
        "</div>",
        unsafe_allow_html=True,
    )


def _progress_bar(current: int) -> None:
    labels = ["1 · Requirements", "2 · Configuration", "3 · Install", "4 · Complete"]
    parts = []
    for i, label in enumerate(labels, 1):
        if   i < current:  cls = "step-done"; icon = "✓ "
        elif i == current: cls = "step-curr"; icon = "● "
        else:              cls = "step-todo"; icon = "○ "
        parts.append(f"<div class='step-item {cls}'>{icon}{label}</div>")
    st.markdown("<div class='step-bar'>" + "".join(parts) + "</div>",
                unsafe_allow_html=True)
    st.markdown("---")


# ── Step 1: Requirements ──────────────────────────────────────────────────────

def _step1_requirements() -> None:
    st.subheader("Step 1 — Server Requirements")
    st.caption("Verifying your environment meets all prerequisites before installation.")

    any_fail = False

    # Python version
    py_ok, py_ver = _check_python()
    if not py_ok:
        any_fail = True
    st.markdown("**Python Interpreter**")
    if py_ok:
        st.success(f"Python {py_ver} ✓  (requires ≥ 3.9)")
    else:
        st.error(f"Python {py_ver} — version 3.9 or newer is required.")

    # Required libraries
    st.markdown("**Required Libraries**")
    import pandas as pd
    lib_rows = []
    for display, imp, min_v in REQUIRED_PACKAGES:
        ok, ver = _check_package(imp)
        if not ok:
            any_fail = True
        lib_rows.append({
            "Package":     display,
            "Installed":   ver,
            "Min Version": f"≥ {min_v}",
            "Status":      "✅" if ok else "❌",
        })
    st.dataframe(pd.DataFrame(lib_rows), use_container_width=True, hide_index=True)

    # Directory permissions
    st.markdown("**Directory Write Permissions**")
    dir_rows = []
    for rel, purpose in WRITE_DIRS:
        ok, msg = _check_writable(rel)
        if not ok:
            any_fail = True
        dir_rows.append({
            "Directory": rel,
            "Purpose":   purpose,
            "Status":    f"✅  {msg}" if ok else f"❌  {msg}",
        })
    st.dataframe(pd.DataFrame(dir_rows), use_container_width=True, hide_index=True)

    st.markdown("")
    if any_fail:
        st.error(
            "One or more requirements are not met.  \n"
            "• Install missing packages: `pip install -r requirements.txt`  \n"
            "• Ensure the listed directories are writable by the server process."
        )
        if st.button("🔄 Re-check", use_container_width=True, key="s1_recheck"):
            st.rerun()
    else:
        st.success("All requirements satisfied — ready to continue.")
        if st.button("Continue →", type="primary", use_container_width=True, key="s1_next"):
            st.session_state.wiz_step = 2
            st.rerun()


# ── Step 2: Configuration ─────────────────────────────────────────────────────

def _step2_configuration() -> None:
    st.subheader("Step 2 — Configuration")
    st.caption("Enter your site settings and create the initial administrator account.")

    saved = st.session_state.get("wiz_cfg", {})

    with st.form("wiz_cfg_form", clear_on_submit=False):

        st.markdown("#### Application")
        c1, c2 = st.columns(2)
        site_name = c1.text_input(
            "Site Name *",
            value=saved.get("site_name", "Analytics Workbench"),
        )
        app_url = c2.text_input(
            "App URL",
            value=saved.get("app_url", "http://localhost"),
            help="The public URL where this instance will be accessible.",
        )

        st.markdown("#### Database")
        db_path = st.text_input(
            "SQLite Database Path",
            value=saved.get("db_path", ""),
            placeholder="Leave blank — default: data/analytics_workbench.db",
            help=(
                "Absolute path to the SQLite .db file. "
                "Leave blank to use the built-in default location."
            ),
        )

        st.markdown("#### Administrator Account")
        c3, c4 = st.columns(2)
        admin_name  = c3.text_input("Full Name *",  value=saved.get("admin_name",  "Admin"))
        admin_email = c4.text_input(
            "Email Address *",
            value=saved.get("admin_email", ""),
            placeholder="admin@example.com",
        )
        c5, c6 = st.columns(2)
        admin_pass  = c5.text_input("Password *",         type="password", value="",
                                    help="Minimum 8 characters.")
        admin_pass2 = c6.text_input("Confirm Password *", type="password", value="")

        col_back, col_spacer, col_next = st.columns([1, 0.3, 3])
        go   = col_next.form_submit_button("Continue →", type="primary",
                                           use_container_width=True)
        back = col_back.form_submit_button("← Back", use_container_width=True)

    if back:
        st.session_state.wiz_step = 1
        st.rerun()

    if go:
        errs: list[str] = []
        if not site_name.strip():
            errs.append("Site Name is required.")
        if not admin_name.strip():
            errs.append("Admin Full Name is required.")
        if not admin_email.strip() or "@" not in admin_email:
            errs.append("A valid Admin Email address is required.")
        if len(admin_pass) < 8:
            errs.append("Password must be at least 8 characters.")
        if admin_pass != admin_pass2:
            errs.append("Passwords do not match.")
        if db_path.strip() and not Path(db_path.strip()).parent.exists():
            errs.append(
                f"Database parent directory does not exist: {Path(db_path.strip()).parent}"
            )

        if errs:
            for e in errs:
                st.error(e)
        else:
            st.session_state.wiz_cfg = {
                "site_name":      site_name.strip(),
                "app_url":        app_url.strip() or "http://localhost",
                "db_path":        db_path.strip(),
                "admin_name":     admin_name.strip(),
                "admin_email":    admin_email.strip(),
                "admin_password": admin_pass,
                "secret_key":     secrets.token_hex(32),
            }
            st.session_state.wiz_step = 3
            st.rerun()


# ── Step 3: Install ───────────────────────────────────────────────────────────

def _step3_install() -> None:
    st.subheader("Step 3 — Installation")

    cfg: dict | None = st.session_state.get("wiz_cfg")
    if not cfg:
        st.error("Configuration is missing — please complete Step 2 first.")
        if st.button("← Back to Configuration", key="s3_nocfg_back"):
            st.session_state.wiz_step = 2
            st.rerun()
        return

    # Already completed — skip forward
    if st.session_state.get("wiz_done"):
        st.session_state.wiz_step = 4
        st.rerun()
        return

    # Summary card
    st.markdown("Review the settings below, then click **Install Now** to proceed.")
    with st.expander("Configuration summary", expanded=True):
        c1, c2 = st.columns(2)
        c1.markdown(f"**Site Name:** {cfg['site_name']}")
        c1.markdown(f"**App URL:** {cfg['app_url']}")
        c1.markdown(f"**DB Path:** `{cfg['db_path'] or 'data/analytics_workbench.db  (default)'}`")
        c2.markdown(f"**Admin Name:** {cfg['admin_name']}")
        c2.markdown(f"**Admin Email:** {cfg['admin_email']}")
        c2.markdown("**Password:** *(hidden)*")

    col_back, _sp, col_install = st.columns([1, 0.3, 3])
    if col_back.button("← Back", key="s3_back", use_container_width=True):
        st.session_state.wiz_step = 2
        st.rerun()

    if not col_install.button("🚀 Install Now", type="primary", key="s3_go",
                               use_container_width=True):
        return

    # ── Run all installation steps with live feedback ─────────────────────────
    install_steps: list[tuple] = [
        ("Writing .env configuration file",              _write_env,      cfg),
        ("Loading environment variables",                _reload_env),
        ("Creating required directories",                _create_dirs),
        ("Testing database connection",                  _test_db,        cfg["db_path"]),
        ("Running database migrations",                  _run_schema,     cfg["db_path"]),
        (f"Creating admin account ({cfg['admin_email']})", _create_admin,
         cfg["admin_email"], cfg["admin_password"], cfg["admin_name"], cfg["db_path"]),
        ("Finalising installation",                      _write_lock),
    ]

    total    = len(install_steps)
    progress = st.progress(0, text="Starting…")
    log_area = st.container()
    results: list[tuple[bool, str]] = []
    failed   = False

    for idx, step in enumerate(install_steps, 1):
        label, fn, *args = step
        progress.progress(idx / total, text=label + "…")
        try:
            fn(*args)
            results.append((True, label))
        except Exception as exc:
            results.append((False, f"{label}: {exc}"))
            failed = True
            break

    progress.empty()

    with log_area:
        for ok, msg in results:
            if ok:
                st.markdown(f"✅ &nbsp; {msg}")
            else:
                st.markdown(f"❌ &nbsp; {msg}")

    if failed:
        st.error(
            "Installation failed at the step shown above. "
            "Fix the issue and click Install Now again."
        )
        return

    st.session_state.wiz_done = True
    time.sleep(0.4)
    st.session_state.wiz_step = 4
    st.rerun()


# ── Step 4: Complete ──────────────────────────────────────────────────────────

def _step4_complete() -> None:
    st.balloons()
    st.success("### ✅ Installation complete!")

    cfg = st.session_state.get("wiz_cfg", {})

    st.markdown(
        "**Analytics Workbench** has been installed and configured successfully. "
        "Click **Launch App** to go directly to the login screen."
    )
    st.markdown("---")

    col_info, col_next = st.columns(2)

    col_info.markdown("**Your login credentials**")
    col_info.markdown(f"- **Email:** `{cfg.get('admin_email', '')}`")
    col_info.markdown("- **Password:** *(as entered during setup)*")

    col_next.markdown("**Post-install checklist**")
    col_next.markdown(
        "- [ ] Log in and verify access  \n"
        "- [ ] Change your password in **Admin → Users**  \n"
        "- [ ] Review site settings in **Admin → Settings**  \n"
        "- [ ] Add external API keys in **Admin → API Keys**"
    )

    st.markdown("---")
    if st.button("🚀 Launch App", type="primary", use_container_width=True, key="s4_launch"):
        # Clear wizard state so it doesn't pollute the main app's session
        for k in list(st.session_state.keys()):
            if k.startswith("wiz_"):
                del st.session_state[k]
        # Rerun — app.py will find .installed and skip this wizard
        st.rerun()


# ── Public entry point ────────────────────────────────────────────────────────

def render_wizard() -> None:
    """Render the correct wizard step.  Called from app.py when .installed is absent."""
    _page_chrome()
    step: int = st.session_state.get("wiz_step", 1)
    _progress_bar(step)

    if   step == 1: _step1_requirements()
    elif step == 2: _step2_configuration()
    elif step == 3: _step3_install()
    elif step == 4: _step4_complete()
    else:
        st.session_state.wiz_step = 1
        st.rerun()
