"""
Analytics Workbench — Web Installation Wizard.

Rendered automatically by app.py when the .installed lock file is absent.
Four steps:
  1  Requirements  — checks Python version, libraries, and dir write permissions
  2  Configuration — site name, database path, initial admin credentials
  3  Installation  — writes .env, creates schema, creates admin account
  4  Complete      — success screen with "Launch App" button
"""
from __future__ import annotations

import importlib
import os
import secrets
import sqlite3
import sys
import time
from pathlib import Path

import streamlit as st

_ROOT = Path(__file__).parent.parent

# ── Required packages ─────────────────────────────────────────────────────────
# (display_name, import_name, min_version_hint)
REQUIRED_PACKAGES: list[tuple[str, str, str]] = [
    ("streamlit",     "streamlit",    "1.28"),
    ("pandas",        "pandas",       "1.3"),
    ("numpy",         "numpy",        "1.21"),
    ("scikit-learn",  "sklearn",      "1.0"),
    ("bcrypt",        "bcrypt",       "3.0"),
    ("cryptography",  "cryptography", "38.0"),
    ("python-dotenv", "dotenv",       "0.19"),
    ("Pillow",        "PIL",          "8.0"),
    ("PyTorch",       "torch",        "1.11"),
]

# Directories that must be writable
WRITE_DIRS: list[tuple[str, str]] = [
    ("data/",         "SQLite database storage"),
    ("session_data/", "Streamlit session persistence"),
    ("logs/",         "Application logs"),
    ("static/",       "Uploaded assets (logos, etc.)"),
]

# ── Requirement checks ────────────────────────────────────────────────────────

def _check_python() -> tuple[bool, str]:
    v = sys.version_info
    return (v.major, v.minor) >= (3, 9), f"{v.major}.{v.minor}.{v.micro}"


def _check_package(import_name: str) -> tuple[bool, str]:
    try:
        mod = importlib.import_module(import_name)
        ver = getattr(mod, "__version__", None) or getattr(mod, "version", "installed")
        return True, str(ver)
    except ImportError:
        return False, "not installed"


def _check_writable(rel: str) -> tuple[bool, str]:
    p = _ROOT / rel
    try:
        p.mkdir(parents=True, exist_ok=True)
        probe = p / ".write_test"
        probe.write_text("ok")
        probe.unlink()
        return True, "writable"
    except Exception as exc:
        return False, str(exc)


def _all_requirements_ok() -> bool:
    if not _check_python()[0]:
        return False
    for _, imp, _ in REQUIRED_PACKAGES:
        if not _check_package(imp)[0]:
            return False
    for d, _ in WRITE_DIRS:
        if not _check_writable(d)[0]:
            return False
    return True


# ── Installation helpers ──────────────────────────────────────────────────────

def _env_file() -> Path:
    """Return the path to write/read the env config file.

    Prefers .env, but falls back to app.env when .env is a directory
    (e.g. when the old-style Python venv lives at .env/).
    admin/db.py tries both names so the app loads whichever exists.
    """
    candidate = _ROOT / ".env"
    if candidate.is_dir():
        return _ROOT / "app.env"
    return candidate


def _write_env(cfg: dict) -> None:
    """Write the env config file from the configuration dict collected in Step 2."""
    lines = [
        "# Analytics Workbench — Environment Configuration",
        "# Generated by the installation wizard.",
        "# Keep this file secret. Do NOT commit it to version control.",
        "",
        f'APP_NAME="{cfg["site_name"]}"',
        "APP_ENV=production",
        "APP_DEBUG=false",
        f'APP_URL={cfg["app_url"]}',
        f'APP_SECRET_KEY={cfg["secret_key"]}',
        "",
        "# SQLite database (leave blank to use default: data/analytics_workbench.db)",
        f'DB_PATH={cfg["db_path"]}',
        "DB_PREFIX=aw_",
        "",
        "STREAMLIT_SERVER_PORT=8501",
        "STREAMLIT_SERVER_ADDRESS=0.0.0.0",
        "STREAMLIT_SERVER_HEADLESS=true",
        "STREAMLIT_BROWSER_GATHER_USAGE_STATS=false",
        "",
        "# Initial superadmin — used during first-launch seeding only",
        f'ADMIN_EMAIL={cfg["admin_email"]}',
        f'ADMIN_PASSWORD={cfg["admin_password"]}',
    ]
    _env_file().write_text("\n".join(lines) + "\n")


def _reload_env() -> None:
    """Push the freshly written env file into the current process's environment."""
    try:
        from dotenv import load_dotenv
        load_dotenv(_env_file(), override=True)
    except ImportError:
        pass  # dotenv unavailable — values were set manually via os.environ


def _create_dirs() -> None:
    for d, _ in WRITE_DIRS:
        (_ROOT / d).mkdir(parents=True, exist_ok=True)


def _test_db(db_path: str) -> None:
    """Verify SQLite can open (or create) the target database file."""
    p = Path(db_path) if db_path else _ROOT / "data" / "analytics_workbench.db"
    p.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(p))
    conn.execute("SELECT 1")
    conn.close()


def _run_schema(db_path: str) -> None:
    """Bootstrap all admin tables (idempotent)."""
    if db_path:
        os.environ["DB_PATH"] = db_path
    from admin.db import ensure_admin_schema
    ensure_admin_schema()


def _create_admin(email: str, password: str, name: str, db_path: str) -> None:
    """Insert the superadmin row, replacing any existing one with the same email."""
    if db_path:
        os.environ["DB_PATH"] = db_path
    import bcrypt
    from admin.db import get_db
    prefix = os.environ.get("DB_PREFIX", "aw_")
    hashed = bcrypt.hashpw(password.encode(), bcrypt.gensalt(12)).decode()
    with get_db() as (_, cur):
        cur.execute(
            f'INSERT OR REPLACE INTO "{prefix}users" '
            f'(name, email, password, role) VALUES (?, ?, ?, "superadmin")',
            (name, email, hashed),
        )


def _write_lock() -> None:
    """Write the .installed flag so the wizard is never shown again."""
    (_ROOT / ".installed").write_text(
        f"installed_at={time.strftime('%Y-%m-%dT%H:%M:%S')}\nversion=1.0.0\n"
    )


